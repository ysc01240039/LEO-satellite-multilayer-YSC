print("\n" + "=" * 70)
print("Part 2: Gamma Scan (n_cores vs chemotactic strength)")
print("=" * 70)

gamma_path = os.path.join(RESULTS_DIR, "gamma_scan_summary.json")
if os.path.exists(gamma_path):
    with open(gamma_path) as f:
        g_data = json.load(f)
    
    gammas = np.array([d["gamma"] for d in g_data])
    n_cores_g = np.array([d["avg_cores"] for d in g_data])
    
    print(f"\n  Data points: {len(gammas)}")
    print(f"  {'γ':>8s}  {'n_cores':>10s}")
    print(f"  {'-'*8}  {'-'*10}")
    for g, n in zip(gammas, n_cores_g):
        print(f"  {g:8.1f}  {n:10.3f}")
    
    # Theory: gamma_c = 1.8895 for beta=0.6
    # For gamma >> gamma_c, n_cores ~ constant (saturation)
    # For gamma just above gamma_c, n_cores ~ m * ln(gamma/gamma_c) or power law
    
    gamma_c_theory = 0.6 * (1 + np.sqrt(0.6))**2  # = 1.8895
    
    # Fit n_cores vs log(gamma) for gamma > gamma_c
    mask_super = gammas > gamma_c_theory
    if np.sum(mask_super) >= 3:
        log_g = np.log(gammas[mask_super] - gamma_c_theory)
        log_n_g = np.log(n_cores_g[mask_super])
        slope_g, _, r_g, _, _ = linregress(log_g, log_n_g)
        print(f"\n  Near critical (γ > γ_c):")
        print(f"    n_cores ∝ (γ - γ_c)^({slope_g:.4f})")
        print(f"    R² = {r_g**2:.6f}")
    
    # Simple log-log fit for all data
    log_g_all = np.log(gammas)
    log_n_all = np.log(n_cores_g)
    slope_all, _, r_all, _, _ = linregress(log_g_all, log_n_all)
    print(f"\n  Global power law: n_cores ∝ γ^({slope_all:.4f})")
    print(f"    R² = {r_all**2:.6f}")
    
    gamma_analysis = {
        "gamma_values": gammas.tolist(),
        "n_cores": n_cores_g.tolist(),
        "gamma_c_theory": gamma_c_theory,
        "global_exponent": float(slope_all),
        "global_R2": float(r_all**2),
    }
else:
    print("\n  [WAITING] gamma_scan_summary.json not yet available")
    gamma_analysis = None

